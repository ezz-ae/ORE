// Account & Treasury namespace. Keys prefixed `wal.` and `bank.`.
//
// START FROM WHAT THE READER ALREADY KNOWS, THEN ADD WHAT WE CHANGED.
//
// These screens are read by management and finance, and they went through two
// wrong versions before this one.
//
// The first was plain speech — "Cash you hold", "Every movement", "Who is
// using what they were given". Readable, and wrong for the audience: somebody
// who reconciles bank statements for a living reads "movement" and has to work
// out whether it means a debit. A screen that needs translating before it can
// be trusted does not get trusted.
//
// The second overcorrected into abstract finance — "Treasury", "issuance
// against company credit", "allocation and utilisation by holder", "drawn
// down". Precise, and worse: not one of those is a word anybody in this
// business says out loud, so every label had to be learned from nothing.
//
// The rule this settled on: a person remembers by CONNECTION, not by storage.
// So every label starts from a word they already hold — bank, cheque, deposit,
// balance, debit, credit, statement, mint, burn — and the sentence beside it
// carries the part this system does differently. A cheque here is not a paper
// instrument, but it means the same thing it always did: money with one
// person's name on it, and only that person can cancel it. Say the familiar
// word, then attach the difference; never invent a word for a thing that
// already has one.
//
// The unit is CASH and one Cash is one dirham (credits-shared.ts). Balances are
// written as Cash rather than AED on purpose: this is company money spendable
// THROUGH the system, and writing it as plain AED beside a bank balance invites
// somebody to read it as funds they can withdraw at a machine.
